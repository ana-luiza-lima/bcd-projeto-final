CREATE TABLE USUARIO (
    id_usuario INT UNSIGNED NOT NULL,
    nickname VARCHAR(50) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    data_cadastro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    saldo_carteira DECIMAL(12, 2) NOT NULL DEFAULT 0.00
);

CREATE TABLE EMPRESA (
    id_empresa INT UNSIGNED NOT NULL,
    nome VARCHAR(150) NOT NULL
);

CREATE TABLE JOGO (
    id_jogo INT UNSIGNED NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    data_lancamento DATE NOT NULL,
    preco_base DECIMAL(10, 2) NOT NULL,
    id_empresa INT UNSIGNED NOT NULL,
    id_jogo_base INT UNSIGNED NULL
);

CREATE TABLE GENERO (
    id_genero INT UNSIGNED NOT NULL,
    nome VARCHAR(80) NOT NULL
);

CREATE TABLE JOGO_GENERO (
    id_jogo INT UNSIGNED NOT NULL,
    id_genero INT UNSIGNED NOT NULL
);

CREATE TABLE CONQUISTA (
    id_jogo INT UNSIGNED NOT NULL,
    id_conquista INT UNSIGNED NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    pontos_xp INT UNSIGNED NOT NULL
);

CREATE TABLE BIBLIOTECA (
    id_usuario INT UNSIGNED NOT NULL,
    id_jogo INT UNSIGNED NOT NULL,
    data_compra DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    preco_pago DECIMAL(10, 2) NOT NULL,
    horas_jogadas DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    nota_avaliacao TINYINT UNSIGNED NULL
);

CREATE TABLE USUARIO_CONQUISTA (
    id_usuario INT UNSIGNED NOT NULL,
    id_jogo INT UNSIGNED NOT NULL,
    id_conquista INT UNSIGNED NOT NULL,
    data_desbloqueio DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
